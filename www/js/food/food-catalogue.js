/* =========================================================
   IGNYT FOOD CATALOGUE — the single front door to every food the app knows about

   Merges four sources behind one API so nothing downstream has to care where a food
   came from:

     seed      273 foods bundled in food-db.js. Short, familiar names and the Indian foods
               USDA has none of. Ranked ABOVE USDA on ties — a user typing "chicken breast"
               wants "Chicken Breast", not "Chicken, Broilers or Fryers, Breast, Meat Only".
     usda      7,697 foods in data/food/clean_foods.json, generated by tools/food-import.
     imported  whatever the user loaded through food-importer.js.
     favourite the user's own saved foods, which food-search.js adds directly.

   WHY LAZY
   clean_foods.json is 3.2 MB. Parsing it costs real time on a mid-range phone, and most app
   sessions never open the food screen at all, so loading it at boot would tax every session
   to benefit some of them. `load()` is called the first time a food UI renders, resolves
   once, and is shared by every later caller through a cached promise. Until it resolves the
   app searches the 273 seed foods — which is exactly the behaviour that shipped before this
   file existed, so a slow or failed load degrades to the old experience rather than an error.

   WHY A MAP
   byId() is called on every render of the food panel. A linear scan of ~8,000 entries per
   render is the kind of thing that turns into a janky keystroke, so ids are indexed once.
========================================================= */
(function () {
  "use strict";

  var DATA_URL = "data/food/clean_foods.json";

  var _usda = [];               // loaded catalogue
  var _merged = null;           // seed + usda + imported, invalidated on change
  var _byId = null;
  var _status = "idle";         // idle | loading | ready | error
  var _promise = null;
  var _error = null;
  var _importedCount = -1;      // change-detector for the imported slice
  var _listeners = [];

  function importedFoods() {
    return window.IgnytFoodImporter ? window.IgnytFoodImporter.catalogue() : [];
  }
  function importedCount() {
    return window.IgnytFoodImporter ? window.IgnytFoodImporter.count() : 0;
  }
  /* The seed catalogue predates the USDA import and named several categories differently for
     the same thing. Left alone that shows up as duplicate tiles in the category browser --
     "Nuts" and "Seeds" sitting next to "Nuts & Seeds", "Oils" next to "Oils & Fats".
     Normalising here rather than editing food-db.js keeps the seed data as the record of what
     was bundled, and keeps the mapping in one visible place.

     serving-converter.js carries matching CATEGORY_UNITS entries for every canonical name on
     the right, so a renamed food keeps its household measures. */
  var SEED_CATEGORY_ALIASES = {
    "Grains": "Grains & Cereals",
    "Bread": "Bread & Bakery",
    "Legumes": "Beans & Legumes",
    "Beans": "Beans & Legumes",
    "Nuts": "Nuts & Seeds",
    "Seeds": "Nuts & Seeds",
    "Oils": "Oils & Fats",
    "Sauces": "Sauces & Condiments"
  };

  function canonicalCategory(c) {
    return Object.prototype.hasOwnProperty.call(SEED_CATEGORY_ALIASES, c)
      ? SEED_CATEGORY_ALIASES[c] : c;
  }

  function seedFoods() {
    if (!window.IgnytFoodDB) return [];
    return window.IgnytFoodDB.all().map(function (f) {
      var canon = canonicalCategory(f.category);
      if (canon === f.category) return f;
      // Copy rather than mutate: IgnytFoodDB hands out its live objects.
      var copy = {};
      for (var k in f) if (Object.prototype.hasOwnProperty.call(f, k)) copy[k] = f[k];
      copy.category = canon;
      return copy;
    });
  }

  /* ---------------------------------------------------------
     Merge
  --------------------------------------------------------- */
  function rebuild() {
    var out = [];
    var seenName = Object.create(null);

    // Seed first so it wins any exact-name collision with USDA.
    seedFoods().forEach(function (f) {
      var k = String(f.name).toLowerCase();
      if (seenName[k]) return;
      seenName[k] = true;
      out.push(f);
    });

    // The user's own imports outrank USDA for the same reason seed foods do: they were
    // added deliberately.
    importedFoods().forEach(function (f) {
      var k = String(f.name).toLowerCase();
      if (seenName[k]) return;
      seenName[k] = true;
      out.push(f);
    });

    _usda.forEach(function (f) {
      var k = String(f.name).toLowerCase();
      if (seenName[k]) return;
      seenName[k] = true;
      out.push(f);
    });

    _merged = out;
    _byId = Object.create(null);
    for (var i = 0; i < out.length; i++) _byId[out[i].id] = out[i];
    _importedCount = importedCount();
  }

  function ensureMerged() {
    // Imported foods change only on an explicit import or clear, so a count comparison is a
    // sufficient and very cheap staleness check.
    if (_merged === null || _importedCount !== importedCount()) rebuild();
    return _merged;
  }

  /* ---------------------------------------------------------
     Load
  --------------------------------------------------------- */
  function load() {
    if (_promise) return _promise;

    _status = "loading";
    _promise = fetch(DATA_URL, { cache: "force-cache" })
      .then(function (res) {
        if (!res.ok) throw new Error("HTTP " + res.status);
        return res.json();
      })
      .then(function (json) {
        var foods = (json && Array.isArray(json.foods)) ? json.foods : [];
        // Trust but verify: a truncated or half-written file should degrade to seed-only
        // rather than poisoning search with malformed entries.
        _usda = foods.filter(function (f) {
          return f && f.id && f.name && typeof f.calories === "number";
        });
        _merged = null;
        _status = "ready";
        notify();
        return _usda.length;
      })
      .catch(function (err) {
        // Not fatal. The seed catalogue still works, which is what the app had before.
        _error = err;
        _status = "error";
        _usda = [];
        _merged = null;
        notify();
        return 0;
      });

    return _promise;
  }

  function notify() {
    var ls = _listeners.slice();
    _listeners.length = 0;
    ls.forEach(function (cb) { try { cb(); } catch (e) { /* a listener must not break load */ } });
  }

  /** Runs `cb` once the catalogue finishes loading (or immediately if it already has). */
  function onReady(cb) {
    if (typeof cb !== "function") return;
    if (_status === "ready" || _status === "error") { cb(); return; }
    _listeners.push(cb);
    load();
  }

  /* ---------------------------------------------------------
     Scaling
  --------------------------------------------------------- */
  var MACROS = ["protein", "carbs", "fat", "fibre", "sugar"];
  var MINERALS = ["sodium", "potassium", "calcium", "iron"];

  /**
   * Scales a food to a gram amount, carrying every nutrient it has.
   *
   * IgnytFoodDB.scaleFood covers only the five macros the food log stores and is left
   * untouched, because the logging path depends on that exact shape. This is the richer
   * version the detail page needs. Nulls stay null: "no data" and "measured zero" are
   * different facts and collapsing them would invent nutrition that was never measured.
   */
  function scale(food, grams) {
    if (!food) return null;
    var basis = food.per || 100;
    var g = Number(grams);
    if (!isFinite(g) || g <= 0) g = basis;
    var f = g / basis;

    var out = {
      id: food.id, name: food.name, category: food.category,
      grams: Math.round(g * 10) / 10,
      calories: Math.round((Number(food.calories) || 0) * f)
    };
    MACROS.forEach(function (k) {
      out[k] = food[k] == null ? null : Math.round(Number(food[k]) * f * 10) / 10;
    });
    MINERALS.forEach(function (k) {
      out[k] = food[k] == null ? null : Math.round(Number(food[k]) * f * 10) / 10;
    });
    return out;
  }

  /* ---------------------------------------------------------
     Queries
  --------------------------------------------------------- */
  function byCategory(category) {
    return ensureMerged().filter(function (f) { return f.category === category; });
  }

  /** Category names with live counts, ordered by count. */
  function categories() {
    var counts = Object.create(null);
    ensureMerged().forEach(function (f) {
      var c = f.category || "Custom Foods";
      counts[c] = (counts[c] || 0) + 1;
    });
    return Object.keys(counts).map(function (name) {
      return { name: name, count: counts[name] };
    }).sort(function (a, b) {
      if (b.count !== a.count) return b.count - a.count;
      return a.name.localeCompare(b.name);
    });
  }

  window.IgnytFoodCatalogue = Object.freeze({
    load: load,
    onReady: onReady,
    status: function () { return _status; },
    error: function () { return _error; },
    isReady: function () { return _status === "ready"; },

    all: function () { return ensureMerged(); },
    count: function () { return ensureMerged().length; },
    usdaCount: function () { return _usda.length; },
    byId: function (id) { ensureMerged(); return _byId[id] || null; },
    byCategory: byCategory,
    categories: categories,

    scale: scale,
    /** Forces a rebuild. Only needed after something mutates a source out of band. */
    invalidate: function () { _merged = null; }
  });
}());
